#!/usr/bin/env python3
"""Turn the capture core's binary into a C source the controller can carry.

The controller image embeds the capture image and copies it into the CM7's ITCM
before releasing that core. That is the SDK's own multicore pattern, and it is
what makes the pair work without a debugger: one image to program, no load
ordering to get right, and the controller knows what is in ITCM because it put
it there.

Generated rather than committed. The blob has to match the capture build exactly
- a stale array would be copied into ITCM and run, which is a failure with no
useful symptom - so it is produced from the .bin at build time.
"""

import argparse
import pathlib
import sys

HEADER = """/*
 * Generated by scripts/mkcm7image.py - do not edit.
 *
 * The capture core image, for the controller to copy into the CM7's ITCM.
 *   source        {name}
 *   size          {size} bytes
 *   initial SP    0x{sp:08X}
 *   reset vector  0x{pc:08X}
 */
#include <stdint.h>

/*
 * const, and it matters which.
 *
 * Only the flexspi_nor target embeds this image, and there .rodata stays in
 * flash - 8 MB of it - so 34 KB costs no RAM at all. Dropping const would move
 * it to .data and buy a needless copy in TCM.
 *
 * The RAM target cannot carry the image either way: that linker script stores
 * .data initialisers in m_text, which the controller already fills to 96% of
 * its 127 KB.
 */
const uint8_t bb_cm7_image[] __attribute__((aligned(4))) = {{
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("binary", type=pathlib.Path,
                    help="capture core .bin, linked at ITCM 0x00000000")
    ap.add_argument("output", type=pathlib.Path, help="C source to write")
    args = ap.parse_args()

    if not args.binary.is_file():
        print("mkcm7image: no such binary: %s" % args.binary, file=sys.stderr)
        return 1

    blob = args.binary.read_bytes()
    if len(blob) < 8:
        print("mkcm7image: %s is only %d bytes; that is not an image"
              % (args.binary, len(blob)), file=sys.stderr)
        return 1

    # The first two words of a Cortex-M image are the initial stack pointer and
    # the reset vector. Checking them turns "the CM7 ran garbage" into a build
    # error, which is the difference between a five-second fix and an afternoon
    # with a debugger.
    sp = int.from_bytes(blob[0:4], "little")
    pc = int.from_bytes(blob[4:8], "little")
    if pc & 1 == 0:
        print("mkcm7image: reset vector 0x%08X has no Thumb bit - is %s really a "
              "Cortex-M binary?" % (pc, args.binary), file=sys.stderr)
        return 1
    if pc >= len(blob):
        print("mkcm7image: reset vector 0x%08X lies outside the %d-byte image, so "
              "it is not linked to 0x00000000" % (pc, len(blob)), file=sys.stderr)
        return 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(name=args.binary.name, size=len(blob), sp=sp, pc=pc))
        for off in range(0, len(blob), 16):
            row = blob[off:off + 16]
            f.write("    " + " ".join("0x%02X," % b for b in row) + "\n")
        f.write("};\n\n")
        f.write("const uint32_t bb_cm7_image_size = %du;\n" % len(blob))

    print("mkcm7image: %s -> %s (%d bytes, SP 0x%08X, PC 0x%08X)"
          % (args.binary.name, args.output.name, len(blob), sp, pc))
    return 0


if __name__ == "__main__":
    sys.exit(main())
